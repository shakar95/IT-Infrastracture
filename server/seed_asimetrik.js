async function runSeeder() {
  console.log('🔄 Wiping existing database records from Supabase...');

  // Delete old data in safe foreign-key order
  await supabase.from('troubleshooting_logs').delete().neq('id', '00000000-0000-0000-0000-000000000000');
  await supabase.from('manual_embeddings').delete().neq('id', '00000000-0000-0000-0000-000000000000');
  await supabase.from('devices').delete().neq('id', '00000000-0000-0000-0000-000000000000');
  await supabase.from('boq_models').delete().neq('id', '00000000-0000-0000-0000-000000000000');
  await supabase.from('categories').delete().neq('id', '00000000-0000-0000-0000-000000000000');

  console.log('✅ Tables wiped cleanly.');

  // 1. Insert Categories
  console.log(`📦 Inserting ${categoriesData.length} refined categories...`);
  const { error: catErr } = await supabase.from('categories').insert(categoriesData);
  if (catErr) {
    console.error('❌ Categories insert failed:', catErr.message);
    process.exit(1);
  }
  console.log('✅ Categories inserted.');

  // 2. Insert BOQ Models
  console.log(`📦 Inserting ${boqModelsData.length} BOQ models from Asimetrik invoice...`);
  const { error: boqErr } = await supabase.from('boq_models').insert(boqModelsData);
  if (boqErr) {
    console.error('❌ BOQ models insert failed:', boqErr.message);
    process.exit(1);
  }
  console.log('✅ BOQ models inserted.');

  // 3. Insert Provisioned Devices (all Pending)
  console.log(`📦 Inserting ${initialDevices.length} initial provisioned devices (status: Pending / Not Configured)...`);
  const { error: devErr } = await supabase.from('devices').insert(initialDevices);
  if (devErr) {
    console.error('❌ Devices insert failed:', devErr.message);
    process.exit(1);
  }
  console.log('✅ Devices inserted with status "Pending" (نۆت کۆنفیگەر).');

  console.log('=================================================================');
  console.log('🎉 ASIMETRIK ICT SYSTEMS BOQ successfully imported to Supabase!');
  console.log('=================================================================');
  process.exit(0);
}

runSeeder().catch((e) => {
  console.error('Fatal seeder error:', e);
  process.exit(1);
});
